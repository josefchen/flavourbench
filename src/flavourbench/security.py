from __future__ import annotations

import hashlib
import hmac
import re

from fastapi import Header, HTTPException

from .config import get_settings

_HEX_64 = re.compile(r"^[0-9a-f]{64}$")
_IDENTITY_LEAK = re.compile(
    r"\b(?:i am|i'm|as an?|powered by|generated by|model\s*[:=]|provider\s*[:=])\s+"
    r"(?:openai|anthropic|claude|chatgpt|gpt[-\s]?\d|gemini|deepseek|qwen|mistral|llama|xai|grok)\b",
    re.IGNORECASE,
)
_EXPLICIT_TOOL_USE = re.compile(
    r"\b(?:epicure\s+(?:mcp|tools?|server)|(?:i|we)\s+"
    r"(?:used|queried|called|accessed|checked|consulted)\s+(?:an?\s+|the\s+)?"
    r"(?:epicure\s+)?(?:external\s+)?(?:tools?|mcp|retrieval)|tool\s+calls?)\b",
    re.IGNORECASE,
)
_CONDITION_DISCLOSURE = re.compile(
    r"\b(?:(?:i|we)\s+(?:had|have|were?\s+given|was\s+given)\s+access\s+to\s+(?:the\s+)?epicure|"
    r"(?:i|we)\s+(?:used|leveraged|queried|consulted|called|accessed)\s+(?:the\s+)?epicure|"
    r"(?:the|an?)\s+(?:epicure\s+)?(?:tool|mcp(?:\s+server)?|retrieval\s+system)\s+"
    r"(?:returned|showed|suggested|reported|provided|found)|"
    r"(?:my|our)\s+(?:epicure\s+)?(?:tool|mcp|retrieval)\s+(?:call\s+)?"
    r"(?:returned|showed|suggested|reported|provided|found))\b",
    re.IGNORECASE,
)
_EPICURE_ATTRIBUTION = re.compile(
    r"\b(?:(?:according\s+to|using|via|from|checked|queried|consulted)\s+"
    r"(?:the\s+)?epicure|epicure(?:'s|’s)\s+(?:pairing\s+)?evidence)\b",
    re.IGNORECASE,
)
_EMAIL = re.compile(r"\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b", re.IGNORECASE)
_PHONE = re.compile(r"(?<!\d)(?:\+?\d[\d .()-]{7,}\d)(?!\d)")


def require_service_token(x_flavourbench_service_token: str = Header(default="")) -> None:
    expected = get_settings().service_token
    if not expected or not hmac.compare_digest(x_flavourbench_service_token, expected):
        raise HTTPException(status_code=401, detail="invalid service token")


def require_admin_token(x_flavourbench_admin_token: str = Header(default="")) -> None:
    expected = get_settings().admin_token
    if not expected or not hmac.compare_digest(x_flavourbench_admin_token, expected):
        raise HTTPException(status_code=401, detail="invalid admin token")


def require_expert_token(authorization: str = Header(default="")) -> str:
    expected = get_settings().expert_token
    supplied = authorization.removeprefix("Bearer ").strip()
    if not expected or not hmac.compare_digest(supplied, expected):
        raise HTTPException(status_code=401, detail="invalid expert invitation")
    return hashlib.sha256(f"expert:{supplied}".encode()).hexdigest()


def request_pseudonym(value: str | None, fallback: str) -> str:
    if value and _HEX_64.fullmatch(value):
        return value
    secret = get_settings().pseudonym_secret.encode()
    return hmac.new(secret, fallback.encode(), hashlib.sha256).hexdigest()


def contains_identity_leak(answer: str, model_name: str = "", prompt: str = "") -> bool:
    if (
        _IDENTITY_LEAK.search(answer)
        or _EXPLICIT_TOOL_USE.search(answer)
        or _CONDITION_DISCLOSURE.search(answer)
    ):
        return True
    if "epicure" not in prompt.lower() and _EPICURE_ATTRIBUTION.search(answer):
        return True
    normalized_name = " ".join(model_name.lower().split())
    return bool(normalized_name and len(normalized_name) > 4 and normalized_name in answer.lower())


def sanitize_for_release(value: str) -> str:
    return _PHONE.sub("[PHONE REDACTED]", _EMAIL.sub("[EMAIL REDACTED]", value))
